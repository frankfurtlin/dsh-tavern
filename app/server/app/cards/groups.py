# Worker side (card_group_chat tasks)


def _message_for_task(db, task_id):
    return db.scalar(select(CardGroupMessage).where(CardGroupMessage.task_id == task_id,
                                                    CardGroupMessage.role == "assistant").with_for_update())


def fail_message(db, task):
    """Called from ``worker.fail_task``: mark the pending reply as failed."""
    message = _message_for_task(db, task.id)
    if message is not None and message.status == "pending":
        message.status = "failed"
    chat = db.get(CardGroupChat, task.payload.get("chatId"))
    if chat is not None:
        chat.updated_at = now()


def process_task(task_id):
    from .. import worker
    worker.check_cancel(task_id)
    with SessionLocal() as db:
        task = worker.lock_task(db, task_id)
        payload = task.payload
        chat = db.get(CardGroupChat, payload.get("chatId"))
        if chat is None or chat.status != "active":
            raise Problem("TASK_CANCELLED", "群聊已删除")
        profile = owned(db, ModelProfile, payload["profileId"], task.owner_id)
        data = {key: payload[key] for key in
                ("cards", "speaker", "conversation", "message", "presetSuffix", "rule")
                if key in payload}
    worker.transition(task_id, "running")
    result = worker.call_provider(task_id, "generation", "card_group_chat", data,
                                  completion_limit(profile, "generation"))
    text = (result.get("text") or "").strip()
    if not text:
        raise Problem("REPLY_EMPTY", "模型没有返回内容", 502, retryable=True)
    with SessionLocal() as db:
        task = worker.lock_task(db, task_id)
        worker.assert_task_active(db, task)
        message = _message_for_task(db, task.id)
        if message is None:
            raise Problem("TASK_CANCELLED", "回复已被删除")
        if message.status == "saved":
            return
        message.text = _clip(space.apply_regex(db, task.owner_id, text), 8000)
        message.status = "saved"
        chat = db.get(CardGroupChat, task.payload.get("chatId"))
        if chat is not None:
            chat.updated_at = now()
            chat.version += 1
        task.state, task.persistence_state, task.result_outcome = "succeeded", "saved", "complete"
        task.result = {**task.result, "chatId": task.payload.get("chatId"), "messageId": message.id,
                       "speakerName": message.speaker_name, "speakerCardId": message.speaker_card_id}
        worker.add_event(db, task, "terminal", {"state": "succeeded", "messageId": message.id})
        db.commit()
