"""Multi-card group chats: rooms, messages and the ``card_group_chat`` worker.

The room stores the ordered card selection plus a plain message log. Every
assistant turn is generated by a normal (non-world) task so it reuses the
existing provider/consent/budget machinery; the speaker is picked by rotation
over the cards at send time and the pending assistant row is updated in place
when the worker finishes.
"""
import json
import logging
from datetime import timedelta

from sqlalchemy import delete, func, select

from ..completion_policy import completion_limit
from ..db import SessionLocal
from ..domain import canonical, digest, idempotent, owned
from ..errors import Problem
from ..execution_prompts import freeze_prompts
from ..model_budget import call_budget_exceeded, input_budget_exceeded, output_budget_exceeded
from ..models import Consent, ModelProfile, OperationPlan, Task, now, uid
from ..prose.policy import freeze
from ..story_flow import TERMINAL, default_profile, stage_budget
from . import space
from .models import CardGroupChat, CardGroupMessage, CharacterCard

logger = logging.getLogger("reader")

MIN_CARDS, MAX_CARDS = 2, 5
HISTORY_LIMIT = 30
CARD_FIELD_LIMIT = 1200
CONVERSATION_FIELD_LIMIT = 1200
MESSAGE_LIMIT = 4000
PAYLOAD_BYTES = 9000


def _clip(value, limit):
    value = value or ""
    return value if len(value) <= limit else value[:limit]


def _chat_cards(db, owner_id, ids):
    rows = {row.id: row for row in db.scalars(select(CharacterCard).where(
        CharacterCard.owner_id == owner_id, CharacterCard.id.in_(list(ids))))}
    for card_id in ids:
        row = rows.get(card_id)
        if row is None or row.deleted_at is not None:
            raise Problem("RESOURCE_NOT_FOUND", "角色卡不存在", 404)
    return [rows[card_id] for card_id in ids]


def _card_names(db, ids):
    rows = db.scalars(select(CharacterCard).where(CharacterCard.id.in_(list(ids))))
    found = {row.id: row.name for row in rows}
    return [{"id": card_id, "name": found.get(card_id, "")} for card_id in ids]


def _last_text(db, chat_id):
    row = db.scalar(select(CardGroupMessage).where(CardGroupMessage.chat_id == chat_id)
                    .order_by(CardGroupMessage.sequence.desc(), CardGroupMessage.id.desc()).limit(1))
    return row.text if row else ""


def chat_out(db, chat):
    return {"id": chat.id, "title": chat.title, "cards": _card_names(db, chat.card_ids or []),
            "lastText": _last_text(db, chat.id), "updatedAt": chat.updated_at.isoformat()}


def list_chats(db, owner_id):
    rows = db.scalars(select(CardGroupChat).where(CardGroupChat.owner_id == owner_id,
                                                  CardGroupChat.status == "active")
                      .order_by(CardGroupChat.updated_at.desc(), CardGroupChat.id.desc()))
    return [chat_out(db, chat) for chat in rows]


def _unique_ids(card_ids):
    unique = []
    for card_id in card_ids:
        if card_id not in unique:
            unique.append(card_id)
    if len(unique) != len(card_ids):
        raise Problem("CARD_SELECTION_INVALID", "角色卡不能重复", 422)
    if not MIN_CARDS <= len(unique) <= MAX_CARDS:
        raise Problem("CARD_SELECTION_INVALID", f"群聊需要 {MIN_CARDS} 至 {MAX_CARDS} 张角色卡", 422)
    return unique


def create_chat(db, owner_id, card_ids, title=None):
    ids = _unique_ids(card_ids)
    cards = _chat_cards(db, owner_id, ids)
    title = (title or "").strip()
    if not title:
        title = "、".join(card.name for card in cards) + " 的群聊"
    title = title[:80]
    chat = CardGroupChat(id=uid(), owner_id=owner_id, title=title, card_ids=ids,
                         status="active", version=1, updated_at=now())
    db.add(chat)
    db.commit()
    return chat_out(db, chat)


def get_chat(db, owner_id, chat_id, *, lock=False):
    chat = owned(db, CardGroupChat, chat_id, owner_id, lock=lock)
    if chat.status != "active":
        raise Problem("RESOURCE_NOT_FOUND", "群聊不存在", 404)
    return chat


def chat_detail(db, owner_id, chat_id):
    chat = get_chat(db, owner_id, chat_id)
    rows = {row.id: row for row in db.scalars(select(CharacterCard).where(
        CharacterCard.id.in_(list(chat.card_ids or []))))}
    cards = []
    for card_id in chat.card_ids or []:
        card = rows.get(card_id)
        if card is None:
            continue
        value = {"id": card.id, "name": card.name, "description": card.description}
        if card.avatar_path:
            value["avatarUrl"] = f"/api/reader/v1/character-cards/{card.id}/avatar"
        cards.append(value)
    messages = list(db.scalars(select(CardGroupMessage).where(CardGroupMessage.chat_id == chat.id)
                               .order_by(CardGroupMessage.sequence, CardGroupMessage.id)))
    return {"chat": chat_out(db, chat), "cards": cards, "messages": [
        {"id": row.id, "role": row.role, "speakerCardId": row.speaker_card_id,
         "speakerName": row.speaker_name, "text": row.text, "status": row.status,
         "createdAt": row.created_at.isoformat()} for row in messages]}


def delete_chat(db, owner_id, chat_id):
    chat = get_chat(db, owner_id, chat_id, lock=True)
    db.execute(delete(CardGroupMessage).where(CardGroupMessage.chat_id == chat.id))
    db.delete(chat)
    db.commit()


def _pending_task(db, owner_id, chat):
    return db.scalar(select(Task).where(Task.owner_id == owner_id, Task.task_type == "card_group_chat",
                                        Task.payload["chatId"].astext == chat.id,
                                        Task.state.not_in(list(TERMINAL)))
                     .order_by(Task.created_at.desc()).limit(1))


def _task_for_turn(db, owner_id, chat, turn_id):
    return db.scalar(select(Task).where(Task.owner_id == owner_id, Task.task_type == "card_group_chat",
                                        Task.payload["chatId"].astext == chat.id,
                                        Task.payload["turnId"].astext == turn_id)
                     .order_by(Task.created_at.desc()).limit(1))


def _speaker_response(task, chat_id):
    payload = task.payload
    return {"taskId": task.id, "chatId": chat_id, "speakerCardId": payload.get("speaker", {}).get("id"),
            "speakerName": payload.get("speaker", {}).get("name", "")}


def _history(db, chat_id):
    rows = list(db.scalars(select(CardGroupMessage).where(CardGroupMessage.chat_id == chat_id,
                                                          CardGroupMessage.status != "failed")
                          .order_by(CardGroupMessage.sequence.desc(), CardGroupMessage.id.desc())
                          .limit(HISTORY_LIMIT)))
    return [{"role": row.role, "speakerName": row.speaker_name,
             "text": _clip(row.text, CONVERSATION_FIELD_LIMIT)} for row in reversed(rows)]


def _payload_size(value):
    return len(json.dumps(value, ensure_ascii=False).encode())


def _fit_payload(data, limit=PAYLOAD_BYTES):
    """Keep the wire payload under the non-world input ceiling. Oldest history
    goes first, then long card fields, then the preset suffix."""
    while _payload_size(data) > limit:
        if data["conversation"]:
            data["conversation"].pop(0)
            continue
        trimmed = False
        for card in data["cards"]:
            for key in ("description", "personality", "scenario", "systemPrompt"):
                if len(card[key]) > 160:
                    card[key] = card[key][:160]
                    trimmed = True
        if trimmed:
            continue
        if len(data["presetSuffix"]) > 200:
            data["presetSuffix"] = data["presetSuffix"][:200]
            continue
        if len(data["message"]) > 400:
            data["message"] = data["message"][:400]
            continue
        break
    return data


def send_message(db, owner_id, request, chat_id, message, turn_id):
    chat = get_chat(db, owner_id, chat_id, lock=True)
    text = (message or "").strip()
    if not text:
        raise Problem("MESSAGE_REQUIRED", "请输入消息", 422)

    def send():
        previous = _task_for_turn(db, owner_id, chat, turn_id)
        if previous is not None:
            if previous.payload.get("message") != text:
                raise Problem("IDEMPOTENCY_CONFLICT", "同一条消息的内容发生变化", 409)
            return _speaker_response(previous, chat.id)
        if _pending_task(db, owner_id, chat) is not None:
            raise Problem("CHAT_PENDING", "上一条回复仍在生成，请稍等", 409)
        cards = _chat_cards(db, owner_id, chat.card_ids or [])
        saved = db.scalar(select(func.count()).select_from(CardGroupMessage).where(
            CardGroupMessage.chat_id == chat.id, CardGroupMessage.role == "assistant",
            CardGroupMessage.status == "saved")) or 0
        speaker = cards[saved % len(cards)]
        profile = default_profile(db, owner_id)
        details = stage_budget(profile, ["generation"])
        if (call_budget_exceeded(profile, details["maxCalls"]) or input_budget_exceeded(profile, details["inputTokens"])
                or output_budget_exceeded(profile, details["outputTokens"])):
            raise Problem("BUDGET_NOT_AUTHORIZED", "当前模型额度不足，请到设置调整额度", 403)
        preset = None
        if chat.preset_id:
            preset = space.get_preset(db, owner_id, chat.preset_id)
        history = _history(db, chat.id)
        resolved = _fit_payload({
            "cards": [{"id": card.id, "name": card.name,
                       "description": _clip(card.description, CARD_FIELD_LIMIT),
                       "personality": _clip(card.personality, CARD_FIELD_LIMIT),
                       "scenario": _clip(card.scenario, CARD_FIELD_LIMIT),
                       "systemPrompt": _clip(card.system_prompt, CARD_FIELD_LIMIT)} for card in cards],
            "speaker": {"id": speaker.id, "name": speaker.name},
            "conversation": history,
            "message": _clip(text, MESSAGE_LIMIT),
            "presetSuffix": preset.system_suffix if preset is not None and preset.enabled else "",
            "rule": "本轮只扮演 speaker，不替读者说话。",
        })
        expires = now() + timedelta(minutes=10)
        plan_hash = digest(canonical({"payload": resolved, "details": details, "profileVersion": profile.version}))
        plan = OperationPlan(id=uid(), owner_id=owner_id, profile_id=profile.id, profile_version=profile.version,
                             payload=resolved, details=details, plan_hash=plan_hash, expires_at=expires)
        authorization = Consent(id=uid(), owner_id=owner_id, plan_id=plan.id, profile_id=profile.id,
                                profile_version=profile.version, plan_hash=plan_hash,
                                max_calls=details["maxCalls"], input_limit=details["inputTokens"],
                                output_limit=details["outputTokens"], expires_at=expires)
        db.add_all([plan, authorization])
        db.flush()
        task = Task(id=uid(), owner_id=owner_id, task_type="card_group_chat",
                    payload={**resolved, "chatId": chat.id, "turnId": turn_id, "profileId": profile.id,
                             "consentId": authorization.id},
                    checkpoint={"snapshotId": None, "completionPolicy": details["completionPolicy"],
                                "calls": {}, "executionProfile": freeze(profile),
                                "executionPrompts": freeze_prompts()})
        db.add(task)
        authorization.task_id = task.id
        sequence = db.scalar(select(func.coalesce(func.max(CardGroupMessage.sequence), 0))
                             .where(CardGroupMessage.chat_id == chat.id)) or 0
        db.add(CardGroupMessage(owner_id=owner_id, chat_id=chat.id, sequence=sequence + 1, role="user",
                                speaker_name="", text=text, task_id=task.id, status="saved"))
        db.add(CardGroupMessage(owner_id=owner_id, chat_id=chat.id, sequence=sequence + 2, role="assistant",
                                speaker_card_id=speaker.id, speaker_name=speaker.name, text="",
                                task_id=task.id, status="pending"))
        chat.updated_at = now()
        chat.version += 1
        db.commit()
        return {"taskId": task.id, "chatId": chat.id, "speakerCardId": speaker.id, "speakerName": speaker.name}

    return idempotent(db, owner_id, "card-group-send:" + chat.id,
                      request.headers.get("idempotency-key"),
                      {"chatId": chat.id, "message": text, "turnId": turn_id}, send)


